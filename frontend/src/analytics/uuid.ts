// UUID v4 generation for analytics ids (session, run, event). Analytics must
// degrade, never throw, when platform APIs are missing (ANALYTICS §4), so this
// falls back from crypto.randomUUID to getRandomValues to Math.random.

export const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

export function newUuid(): string {
  try {
    const id = crypto.randomUUID()
    if (typeof id === 'string' && UUID_PATTERN.test(id)) return id
  } catch {
    // fall through to the fallbacks
  }
  const bytes = new Uint8Array(16)
  try {
    crypto.getRandomValues(bytes)
  } catch {
    for (let i = 0; i < bytes.length; i++) bytes[i] = Math.floor(Math.random() * 256)
  }
  bytes[6] = (bytes[6] & 0x0f) | 0x40
  bytes[8] = (bytes[8] & 0x3f) | 0x80
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}
